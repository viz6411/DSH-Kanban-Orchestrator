// Writes a curl-compatible cookie jar for the HTTP API checks: opens the Harness Web GUI with the launch token
// that the service prints at start, then exports the session cookies it received.
import { execSync } from 'node:child_process'
import fs from 'node:fs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const token = execSync('journalctl --user -u dsh-web.service --no-pager -n 4000 2>/dev/null | grep -oE "\\?token=[A-Za-z0-9_-]{16,}" | tail -1', { encoding: 'utf8' }).trim().replace(/^\?token=/, '')
if (!token) { console.log('no launch token in the journal'); process.exit(1) }
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] })
const context = await browser.newContext()
const page = await context.newPage()
await page.goto(`http://192.168.64.230:3080/?token=${token}`, { waitUntil: 'domcontentloaded', timeout: 45000 })
await page.waitForTimeout(6000)
const cookies = await context.cookies()
const lines = ['# Netscape HTTP Cookie File', '# regenerated by tools/browser-checks/refresh-cookie.mjs']
for (const c of cookies) {
  const domain = c.domain.startsWith('.') ? c.domain : c.domain
  lines.push([domain, String(Boolean(c.domain.startsWith('.'))), c.path, String(Boolean(c.secure)), String(Math.round(c.expires > 0 ? c.expires : 0)), c.name, c.value].join('\t'))
}
fs.writeFileSync(process.env.JAR || '/tmp/dshjar.txt', lines.join('\n') + '\n', { mode: 0o600 })
console.log('cookies written:', cookies.map((c) => c.name).join(','))
await browser.close()
